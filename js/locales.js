export const localeCodes = locales.map((l) => l.code);
export const isLocale = (value) => localeCodes.includes(value);
export function resolveLocale({ path = "", stored = "", browser = "en" } = {}) {
  const explicit = path.split("/")[1];
  return isLocale(explicit)
    ? explicit
    : isLocale(stored)
      ? stored
      : localeCodes.includes(browser.toLowerCase().split(/[-_]/)[0])
        ? browser.toLowerCase().split(/[-_]/)[0]
        : "en";
}
